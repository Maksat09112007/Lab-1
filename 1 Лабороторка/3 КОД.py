# Запрашиваем ввод числа у пользователя
num = int(input("Введите трехзначное число: "))

# Извлекаем цифры математически
units = num % 10          # Последняя цифра (единицы)
tens = (num // 10) % 10   # Средняя цифра (десятки)
hundreds = num // 100     # Первая цифра (сотни)

# Собираем число в обратном порядке
reversed_num = units * 100 + tens * 10 + hundreds

# Выводим результат
print(reversed_num)
