# Вводим четырехзначное число как строку или целое число
num = int(input("Введите четырехзначное число: "))

# Находим каждую цифру с помощью деления и остатка
thousands = num // 1000
hundreds = (num // 100) % 10
tens = (num // 10) % 10
ones = num % 10

# Выводим результат
print(f"Тысячи: {thousands}")
print(f"Сотни: {hundreds}")
print(f"Десятки: {tens}")
print(f"Единицы: {ones}")
