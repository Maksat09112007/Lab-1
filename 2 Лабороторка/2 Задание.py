# Ввод четырехзначного числа
num = int(input("Введите четырехзначное число: "))

# Разложение на цифры с конца
digit4 = num % 10          # Последняя цифра
digit3 = (num // 10) % 10  # Предпоследняя цифра
digit2 = (num // 100) % 10 # Вторая цифра
digit1 = num // 1000       # Первая цифра

# Сборка числа в обратном порядке
reversed_num = digit4 * 1000 + digit3 * 100 + digit2 * 10 + digit1

print("Число в обратном порядке:", reversed_num)
