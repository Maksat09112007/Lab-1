import math

# Ввод длины и ширины (используем float для поддержки дробных чисел)
a = float(input("Введите длину прямоугольника: "))
b = float(input("Введите ширину прямоугольника: "))

# Вычисления
S = a * b                # Площадь
P = 2 * (a + b)          # Периметр
d = math.sqrt(a**2 + b**2)  # Длина диагонали (по теореме Пифагора)

# Вывод результатов
print(f"Площадь: {S}")
print(f"Периметр: {P}")
print(f"Длина диагонали: {d}")
