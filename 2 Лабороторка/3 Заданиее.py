# Запрос данных у пользователя
P = float(input("Введите сумму вклада: "))
r_percent = float(input("Введите годовую ставку (в %): "))
t = float(input("Введите срок вклада (в годах): "))

# Перевод процентов в десятичную дробь
r = r_percent / 100

# Вычисление итоговой суммы при ежегодной капитализации
A = P * (1 + r) ** t

# Вывод результата
print(f"\nИтоговая сумма вклада составит: {A:.2f}")
print(f"Чистый доход (проценты): {A - P:.2f}")
